import unittest
from unittest import mock

from tests.helpers import PASSED, SHA, FakeGitHub, response, use_github
from vader import config, report
from vader.agents import VALIDATORS
from vader.engine import Events, Review
from vader.github import GitHubPoller


def passed_review(**changes) -> Review:
    r = Review(source="github", validators=list(VALIDATORS), title="Add order search",
               meta={"repo": "o/r", "number": 42, "sha": SHA, "pr_key": "o/r#42",
                     "url": "https://github.com/o/r/pull/42"})
    r.status, r.verdict, r.verdict_reason = "done", "PASS", "no findings above info; no CI results"
    r.started, r.finished, r.model = 100.0, 160.0, "m:1b"
    for k, v in changes.items():
        setattr(r, k, v)
    return r


class AutoMergeTests(unittest.TestCase):
    def setUp(self):
        self.events = Events()
        self.state = mock.Mock(enabled=True)
        self.state.held_reason.return_value = None
        self.poller = GitHubPoller(self.state, self.events, mock.Mock())
        use_github(self)
        for p in [mock.patch.object(config, "AUTO_MERGE_BRANCH", "staging"),
                  mock.patch("vader.github.time.sleep")]:
            self.enterContext(p)

    def merge(self, review=None) -> dict | None:
        review = review or passed_review()
        self.poller.merge_if_passed(review)
        return review.merge

    def test_a_passing_pr_is_merged_at_the_reviewed_commit(self):
        result = self.merge()
        self.assertEqual(self.gh.merges, [("/repos/o/r/pulls/42/merge", {"sha": SHA, "merge_method": "merge"})])
        self.assertEqual(result["status"], "merged")
        self.assertIn("Merged into `staging`", result["message"])
        event, = [e for e in self.events.since(0) if e["type"] == "pr_merge"]
        self.assertEqual((event["status"], event["review"]["merge"]["status"]), ("merged", "merged"))

    def test_skipped_lockfiles_and_generated_code_dont_stop_a_merge(self):
        # A normal EF migration: a new migration (reviewed), its new Designer file, and the updated snapshot.
        banner = "// <auto-generated />\nusing System;\n"
        self.gh.files.update({"Migrations/AppDbContextModelSnapshot.cs": banner, "Migrations/2026_Init.Designer.cs": banner})
        self.gh.base_files["Migrations/AppDbContextModelSnapshot.cs"] = banner
        review = passed_review(diff="diff --git a/Migrations/2026_Init.cs b/Migrations/2026_Init.cs\n+x\n",
                               skipped_files=[
            {"path": "package-lock.json", "reason": "lockfile"},
            {"path": "Migrations/AppDbContextModelSnapshot.cs", "reason": "generated"},  # had its banner before
            {"path": "Migrations/2026_Init.Designer.cs", "reason": "generated"},  # new, next to its migration
            {"path": "Migrations/Old.Designer.cs", "reason": "generated"}])  # deleted in the PR
        self.assertEqual(self.merge(review)["status"], "merged")

    def test_a_copied_banner_doesnt_make_a_file_safe_to_merge_unread(self):
        banner = "// <auto-generated />\nnamespace App;\n"
        cases = {
            "a new file with nothing it was generated from": ({"Helpers.g.cs": banner}, {}),
            "a banner added in this PR": ({"Helpers.g.cs": banner}, {"Helpers.g.cs": "namespace App;\n"}),
            "an edit to a generated file without its source": ({"Helpers.g.cs": banner}, {"Helpers.g.cs": banner}),
        }
        for what, (head, base) in cases.items():
            with self.subTest(what):
                self.gh = FakeGitHub()
                self.gh.files, self.gh.base_files = head, base
                result = self.merge(passed_review(skipped_files=[{"path": "Helpers.g.cs", "reason": "generated"}]))
                self.assertEqual(result["status"], "skipped")
                self.assertIn("`Helpers.g.cs` (named like generated code", result["message"])
                self.assertEqual(self.gh.merges, [])

    def test_ci_is_read_again_at_merge_time(self):
        # CI was still running when the review started; it has passed since.
        review = passed_review(ci=[{"name": "build-test", "status": "in_progress", "conclusion": None}])
        self.assertEqual(self.merge(review)["status"], "merged")
        self.assertEqual(review.ci, PASSED)

    def test_a_conflict_asks_for_the_branch_to_be_updated(self):
        self.gh.pr["mergeable"] = False
        result = self.merge()
        self.assertEqual(self.gh.merges, [])
        self.assertEqual(result["status"], "conflict")
        self.assertIn("`add-order-search` has merge conflicts with `staging`", result["message"])
        self.assertIn("up to date with `staging`", result["message"])

    def test_github_still_working_out_mergeability_is_asked_again(self):
        answers = iter([None, None, False])
        get = self.gh.get
        self.gh.get = lambda path, **kw: (response(200, dict(self.gh.pr, mergeable=next(answers)))
                                          if path.endswith("/pulls/42") else get(path, **kw))
        self.assertEqual(self.merge()["status"], "conflict")

    def test_github_refusing_the_merge(self):
        cases = [  # (reply to the merge, expected status, words in the message)
            (response(405, {"message": "Pull Request is not mergeable"}), "conflict", "merge conflicts"),
            (response(405, {"message": "At least 1 approving review is required"}), "failed",
             "At least 1 approving review is required"),
            (response(403, {"message": "Resource not accessible by personal access token"}), "failed",
             "Contents: Read and write"),
            (response(409, {"message": "Head branch was modified"}), "skipped", "a newer commit was pushed"),
        ]
        for reply, status, words in cases:
            with self.subTest(status=reply.status_code, message=reply.json()["message"]):
                self.gh = FakeGitHub()
                self.gh.pr["mergeable"] = None  # still unknown, so Vader tries and GitHub answers
                self.gh.merge_reply = reply
                result = self.merge()
                self.assertEqual(result["status"], status)
                self.assertIn(words, result["message"])

    def test_no_attempt_without_a_pass_on_a_pr(self):
        cases = {"MINOR": passed_review(verdict="MINOR"), "HOLD": passed_review(verdict="HOLD"),
                 "BLOCK": passed_review(verdict="BLOCK"), "a pasted diff": passed_review(meta={})}
        for what, review in cases.items():
            with self.subTest(what):
                self.assertIsNone(self.merge(review))
        with mock.patch.object(config, "AUTO_MERGE_BRANCH", ""):
            self.assertIsNone(self.merge())  # off
        self.assertEqual((self.gh.merges, self.events.since(0)), ([], []))

    def test_reasons_a_pass_is_not_merged(self):
        def named_generated_without_a_banner():
            self.gh.files["Helpers.generated.cs"] = "namespace App;\npublic static class H {}"
            return passed_review(skipped_files=[{"path": "Helpers.generated.cs", "reason": "generated"}])

        cases = {
            "only a review by all six validators": lambda: passed_review(validators=["security"]),
            "Vader is stopped": lambda: setattr(self.state, "enabled", False),
            "CI failed": lambda: setattr(self.gh, "checks",
                                         [{"name": "build-test", "status": "completed", "conclusion": "failure"}]),
            "CI hasn't passed yet": lambda: setattr(self.gh, "checks",
                                                    [{"name": "build-test", "status": "in_progress", "conclusion": None}]),
            "add a workflow that builds and runs the tests": lambda: setattr(self.gh, "checks", []),
            "a newer commit was pushed": lambda: self.gh.pr["head"].update(sha="fff0000"),
            "it's a draft": lambda: self.gh.pr.update(draft=True),
            "it targets `main`": lambda: self.gh.pr["base"].update(ref="main"),
            "already merged": lambda: self.gh.pr.update(state="closed", merged=True),
            "the PR is closed": lambda: self.gh.pr.update(state="closed"),
            "an earlier review of this same commit held it (HOLD: rate limit ignored)":
                lambda: setattr(self.state.held_reason, "return_value", "HOLD: rate limit ignored"),
            "hand-written or tampered code: `x/mock.go` (marked as generated)": lambda: passed_review(
                skipped_files=[{"path": "go.sum", "reason": "lockfile"},
                               {"path": "x/mock.go", "reason": "marked as generated"}]),
            # The target moved on after CI ran: the merged result was never tested.
            "is 4 commit(s) behind `staging`, so CI and this review never saw it together with them":
                lambda: setattr(self.gh, "behind_by", 4),
            "couldn't check whether `add-order-search` is up to date": lambda: setattr(self.gh, "behind_by", None),
            "`wwwroot/js/a.js` (compiled from TypeScript)": lambda: passed_review(
                skipped_files=[{"path": "wwwroot/js/a.js", "reason": "compiled from TypeScript"}]),
            "`package-lock.json` (lockfile changed without package.json)": lambda: passed_review(
                skipped_files=[{"path": "package-lock.json", "reason": "lockfile changed without package.json"}]),
            "`Helpers.generated.cs` (named like generated code, but it doesn't start with a generator's banner":
                named_generated_without_a_banner,
        }
        for reason, setup in cases.items():
            with self.subTest(reason):
                self.gh, self.state.enabled = FakeGitHub(), True
                self.state.held_reason.return_value = None
                review = setup()
                result = self.merge(review if isinstance(review, Review) else None)
                self.assertEqual(result["status"], "skipped")
                self.assertIn(reason, result["message"])
                self.assertEqual(self.gh.merges, [])

    def test_paths_that_always_need_a_person_stop_a_merge(self):
        globs = ["src/App.Billing/**", "src/App.Web/Services/PaymentService.cs", "appsettings*.json"]
        self.enterContext(mock.patch.object(config, "NEEDS_PERSON_PATHS", globs))
        cases = {
            "an edit": [{"filename": "src/App.Billing/Models/Invoice.cs", "status": "modified"}],
            "a settings file in any folder": [{"filename": "src/App.Web/appsettings.Production.json"}],
            "a different case": [{"filename": "SRC/app.billing/Tax.cs"}],
            "a file moved out": [{"filename": "src/App.Web/Legacy/PaymentService.cs",
                                  "previous_filename": "src/App.Web/Services/PaymentService.cs",
                                  "status": "renamed"}],
            "a file moved in": [{"filename": "src/App.Billing/Helpers.cs",
                                 "previous_filename": "src/App.Web/Helpers.cs", "status": "renamed"}],
            "past the first page": [{"filename": f"wwwroot/img/{i}.png"} for i in range(100)]
                                   + [{"filename": "src/App.Billing/Tax.cs"}],
        }
        for name, files in cases.items():
            with self.subTest(name):
                self.gh.pr_files, self.gh.merges = files, []
                result = self.merge()
                self.assertEqual((result["status"], self.gh.merges), ("skipped", []))
                self.assertIn("which a person always reviews (`NEEDS_PERSON_PATHS`). This isn't a problem the "
                              "review found", result["message"])
        self.gh.pr_files, self.gh.merges = None, []
        self.assertIn("couldn't list every file the PR changes", self.merge()["message"])
        self.gh.pr_files = [{"filename": "src/App.Web/Views/Home.cshtml"},
                            {"filename": "src/App.Web/Services/PaymentServiceTests.cs"}]
        self.assertEqual(self.merge()["status"], "merged")

    def test_finish_merges_first_so_the_pr_comment_says_what_happened(self):
        self.gh.pr["mergeable"] = False
        with mock.patch.object(config, "GITHUB_COMMENT", True):
            self.poller.finish(passed_review())
        (number, body), = self.gh.comments
        self.assertEqual(number, 42)
        self.assertIn("merge conflicts with `staging`", body)


class MergeReportTests(unittest.TestCase):
    def test_pr_comment_shows_the_merge(self):
        merged = passed_review(merge={"status": "merged", "branch": "staging", "message": "Merged into `staging`."})
        self.assertIn("🔀 Merged into `staging`", report.markdown(merged))
        self.assertNotIn("Merged", report.markdown(passed_review()))


